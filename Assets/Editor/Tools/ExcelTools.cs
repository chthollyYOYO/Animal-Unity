        private static void GenCustomCode()
        {
            List<string> tableNames = new();
            var lines = File.ReadAllLines(clientTableCodePath);
            for (int i = 0; i < lines.Length; i++)
            {
                if (lines[i].Contains("loader("))
                {
                    var index = lines[i].IndexOf('\"') + 1;
                    var lastIndex = lines[i].LastIndexOf('\"');
                    if (index > 0 && lastIndex > index)
                    {
                        var tableName = lines[i].Substring(index, lastIndex - index);
                        tableNames.Add(tableName);
                    }
                }
            }

            string code =
@"
//------------------------------------------------------------------------------
// <auto-generated>
//     This code was generated by a tool.
//     Changes to this file may cause incorrect behavior and will be lost if
//     the code is regenerated.
// </auto-generated>
//------------------------------------------------------------------------------

namespace cfg
{
    public partial class Tables
    {
        public static string[] tableNames;

        static Tables()
        {
            tableNames = new string[] {
%tb_names%
            };
        }
    }
}";
            string tb_names = "";
            for (int i = 0; i < tableNames.Count; i++)
            {
                tb_names += $"\t\t\t\t\"{tableNames[i]}\",";
                if (i != tableNames.Count - 1)
                    tb_names += '\n';
            }

            code = code.Replace("%tb_names%", tb_names);
            File.WriteAllText(clientTableCustomCodePath, code);
        }

        private static void GenCustomCode2()
        {
            string code =
@"
//------------------------------------------------------------------------------
// <auto-generated>
//     This code was generated by a tool.
//     Changes to this file may cause incorrect behavior and will be lost if
//     the code is regenerated.
// </auto-generated>
//------------------------------------------------------------------------------

using System;
using System.Collections.Generic;
using cfg;

namespace Framework
{
    public partial class ConfigManager
    {%subCodes%
    }
}";

            string subCodes = "";
            var table = ReadExcel(clientTablesPath).First().Value;
            for (int i = 3; i < table.Count; i++)
            {
                var row = table[i];
                string fieldName; //字段名
                if (row[1].Contains('.'))
                {
                    var strs = row[1].Split('.');
                    fieldName = strs[strs.Length - 1];
                }
                else
                {
                    fieldName = row[1];
                }
                var className = row[2]; //类名

                var subCode =
@"
        public static %className% Get%className%(int id, bool error = true)
        {
            TryGet%className%(id, out %className% cfg, error);
            return cfg;
        }

        public static bool TryGet%className%(int id, out %className% cfg, bool error = true)
        {
            cfg = tables.%fieldName%.GetOrDefault(id);
            if (cfg == null)
            {
                if (error)
                    UnityEngine.Debug.LogError($""表%className%不存在配置id=({id})"");
                return false;
            }
            return true;
        }

        public static %className% Find%className%(Predicate<%className%> predicate, bool error = true)
        {
            for (int i = 0; i < tables.%fieldName%.DataList.Count; i++)
                if (predicate(tables.%fieldName%.DataList[i]))
                    return tables.%fieldName%.DataList[i];
            if (error)
                UnityEngine.Debug.LogError($""没有找到满足条件的%className%"");
            return null;
        }

        public static Dictionary<int, %className%> Get%className%Map()
        {
            return tables.%fieldName%.DataMap;
        }

        public static List<%className%> Get%className%List()
        {
            return tables.%fieldName%.DataList;
        }
";

                subCode = subCode.Replace("%fieldName%", fieldName);
                subCode = subCode.Replace("%className%", className);
                subCodes += subCode;
            }

            code = code.Replace("%subCodes%", subCodes);
            File.WriteAllText(clientConfigManagerCodePath, code);
        }

        //<tableName, row<field>>
        private static Dictionary<string, List<string[]>> ReadExcel(string path)
        {
            string tempExcelPath = $"{tempPath}/__table__temp.xlsx";
            File.Copy(path, tempExcelPath);

            Dictionary<string, List<string[]>> result = new();
            using var stream = File.OpenRead(tempExcelPath);
            using var reader = ExcelReaderFactory.CreateOpenXmlReader(stream);
            do
            {
                string tableName = reader.Name;
                int fieldCount = reader.FieldCount;
                List<string[]> rows = new();
                for (int i = 0; i < reader.RowCount; i++)
                {
                    reader.Read();
                    string[] fields = new string[fieldCount];
                    for (int j = 0; j < fieldCount; j++)
                    {
                        var value = reader.GetValue(j);
                        if (value != null)
                            fields[j] = value.ToString();
                    }
                    rows.Add(fields);
                }
                result.Add(tableName, rows);
            }
            while (reader.NextResult());
            return result;
        }

